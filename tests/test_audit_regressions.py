@pytest.mark.browser
async def test_revocation_while_injecting_does_not_even_fill_the_old_tab(connected_edge):
    provider, page, worker = connected_edge
    await provider.status()  # Inject once, before adding the delayed API wrapper.
    await worker.evaluate("""() => {
      const original=chrome.scripting.executeScript.bind(chrome.scripting);
      globalThis.injectionPending=false;
      chrome.scripting.executeScript=async (...args) => {
        globalThis.injectionPending=true;
        await new Promise(resolve => {globalThis.releaseInjection=resolve;});
        return original(...args);
      };
    }""")
    task = asyncio.create_task(provider.send("Must not enter revoked composer"))
    try:
        for _ in range(100):
            if await worker.evaluate("globalThis.injectionPending"):
                break
            await asyncio.sleep(0.01)
        assert await worker.evaluate("globalThis.injectionPending")
        await worker.evaluate("""async () => {
          await chrome.storage.session.clear(); globalThis.releaseInjection();
        }""")
        await asyncio.sleep(0.3)
        assert await page.locator("textarea").input_value() == ""
        assert await page.evaluate("window.sentCount") == 0
    finally:
        task.cancel()
        await asyncio.gather(task, return_exceptions=True)


@pytest.mark.browser
async def test_old_content_listener_cannot_receive_new_submit_commands(connected_edge):
    provider, page, worker = connected_edge
    await worker.evaluate("""async () => {
      const {tabId}=await chrome.storage.session.get('tabId');
      await chrome.scripting.executeScript({target:{tabId},world:'ISOLATED',func:() => {
        globalThis.__pilotpatchDriver=2;
        chrome.runtime.onMessage.addListener(message => {
          if (message.type === 'pilotpatch-command-v2' && message.command.action === 'submit') {
            document.body.dataset.oldListenerSubmitted='true';
          }
          return false;
        });
      }});
    }""")
    assert await provider.send("Use the upgraded content channel") == "Complete fixture answer"
    assert await page.locator("body").get_attribute("data-old-listener-submitted") is None
    assert await page.evaluate("window.sentCount") == 1
